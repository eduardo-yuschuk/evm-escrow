// Generates src/generated/contracts.ts with the ABI and creation bytecode of the contracts the API
// uses, from the Foundry artifacts. The output is committed, so the API image never compiles contracts.
//
// Usage: docker compose run --rm forge build && docker compose run --rm npm run abi
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { z } from "zod";

// In the npm service ./contracts is mounted read-only at /contracts (see docker-compose.yml).
const contractsOut =
  process.env.CONTRACTS_OUT ?? path.resolve(import.meta.dirname, "../../contracts/out");
const outputFile = path.resolve(import.meta.dirname, "../src/generated/contracts.ts");

const contracts = [
  { name: "escrow", artifact: "Escrow.sol/Escrow.json" },
  { name: "mockErc20", artifact: "MockERC20.sol/MockERC20.json" },
  // Only for the tests: withdrawals where what the escrow pays and what the holder gets differ, and
  // a token that can block the holder.
  { name: "feeOnTopErc20", artifact: "FeeOnTopERC20.sol/FeeOnTopERC20.json" },
  { name: "blacklistErc20", artifact: "BlacklistERC20.sol/BlacklistERC20.json" },
] as const;

const artifactSchema = z.object({
  abi: z.array(z.record(z.string(), z.unknown())).min(1),
  bytecode: z.object({ object: z.string().regex(/^0x([0-9a-f]{2})+$/) }),
});

async function readArtifact(relativePath: string) {
  const file = path.join(contractsOut, relativePath);
  let raw: string;
  try {
    raw = await readFile(file, "utf8");
  } catch {
    throw new Error(`${file} not found: run \`docker compose run --rm forge build\` first`);
  }
  return artifactSchema.parse(JSON.parse(raw));
}

const sections: string[] = [];
for (const { name, artifact } of contracts) {
  const { abi, bytecode } = await readArtifact(artifact);
  sections.push(
    `export const ${name}Abi = ${JSON.stringify(abi, null, 2)} as const;`,
    `export const ${name}Bytecode = "${bytecode.object}" as const;`,
  );
}

const header = "// Generated by `npm run abi` from the Foundry artifacts. Do not edit.";
await mkdir(path.dirname(outputFile), { recursive: true });
await writeFile(outputFile, [header, ...sections].join("\n\n") + "\n");
console.log(`Wrote ${path.relative(process.cwd(), outputFile)}`);
